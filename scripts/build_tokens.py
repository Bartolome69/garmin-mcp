"""Generate the native apps' design tokens from the PWA's stylesheet.

garmin_mcp/app/app.css is the one source of truth for Daash's colours: its
:root block is dark mode, :root[data-theme="light"] is light mode (repeated
inside a prefers-color-scheme media query, which this checks stays identical).
This reads both and writes:

    mobile/src/theme/tokens.ts    the React Native app's colours, radius and fonts
    mobile/src/theme/design-tokens.json  the same, for native code that can't import TS
                                  (iOS widgets, Android Glance) once those exist

so web and native never drift. Change a colour in app.css, run this, commit both.

    python3 scripts/build_tokens.py          # write the files
    python3 scripts/build_tokens.py --check  # exit 1 if they're out of date (CI)

Standard library only. See docs/native-app/PLAN.md, "Design tokens".
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSS = ROOT / "garmin_mcp" / "app" / "app.css"
OUT_TS = ROOT / "mobile" / "src" / "theme" / "tokens.ts"
OUT_JSON = ROOT / "mobile" / "src" / "theme" / "design-tokens.json"  # not tokens.json: the root .gitignore keeps that name for Garmin credentials

# Custom properties that aren't colours: carried across as their own groups.
NOT_COLOURS = {"radius", "sans", "mono", "desk-max"}
COLOUR = re.compile(r"^(#[0-9A-Fa-f]{3,8}|rgba?\([^)]*\))$")
DECL = re.compile(r"--([a-z0-9-]+)\s*:\s*([^;]+);")


class TokenError(Exception):
    pass


def _block(css: str, selector: str) -> str:
    """The body of the first rule whose selector is exactly `selector` (no nesting inside)."""
    match = re.search(r"(?m)^\s*" + re.escape(selector) + r"\s*\{([^{}]*)\}", css)
    if not match:
        raise TokenError(f"app.css has no `{selector} {{ ... }}` block")
    return match.group(1)


def _decls(body: str) -> dict[str, str]:
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    return {name: " ".join(value.split()) for name, value in DECL.findall(body)}


def camel(name: str) -> str:
    head, *rest = name.split("-")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def read_tokens(css: str) -> dict:
    dark_all = _decls(_block(css, ":root"))
    light = _decls(_block(css, ':root[data-theme="light"]'))
    media = re.search(r'@media \(prefers-color-scheme: light\)\s*\{\s*:root:not\(\[data-theme="dark"\]\)\s*\{([^{}]*)\}',
                      css)
    if not media:
        raise TokenError("app.css has no prefers-color-scheme: light block")
    if _decls(media.group(1)) != light:
        raise TokenError("app.css's two light blocks differ: the media query and :root[data-theme=\"light\"] "
                         "must hold the same colours")
    dark = {k: v for k, v in dark_all.items() if k not in NOT_COLOURS}
    for name, value in {**dark, **light}.items():
        if not COLOUR.match(value):
            raise TokenError(f"--{name}: {value} isn't a colour this generator knows (hex or rgba)")
    missing_light = sorted(set(dark) - set(light))
    extra_light = sorted(set(light) - set(dark))
    if missing_light or extra_light:
        raise TokenError(f"dark and light colours don't pair up: no light value for {missing_light}, "
                         f"no dark value for {extra_light}")
    radius = dark_all.get("radius", "12px")
    return {
        "colors": {
            "dark": {camel(k): dark[k] for k in dark},
            "light": {camel(k): light[k] for k in dark},
        },
        "radius": int(re.sub(r"px$", "", radius)),
        # The PWA bundles Geist and Geist Mono; the native apps use the same families.
        "fonts": {"sans": "Geist", "mono": "GeistMono"},
    }


HEADER = ("// Generated by scripts/build_tokens.py from garmin_mcp/app/app.css. Do not edit:\n"
          "// change app.css, then run `npm run tokens` (or python3 scripts/build_tokens.py).\n")


def render_ts(tokens: dict) -> str:
    colours = json.dumps(tokens["colors"], indent=2)
    return (HEADER + "\n"
            f"export const colors = {colours} as const;\n\n"
            "export type ColorScheme = keyof typeof colors;\n"
            "export type ColorName = keyof (typeof colors)['dark'];\n\n"
            f"export const radius = {tokens['radius']};\n\n"
            f"export const fonts = {json.dumps(tokens['fonts'])} as const;\n")


def render_json(tokens: dict) -> str:
    return json.dumps({"_generated": "scripts/build_tokens.py from garmin_mcp/app/app.css; do not edit", **tokens},
                      indent=2) + "\n"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    try:
        tokens = read_tokens(CSS.read_text())
    except TokenError as exc:
        print(f"build_tokens: {exc}", file=sys.stderr)
        return 1
    wanted = {OUT_TS: render_ts(tokens), OUT_JSON: render_json(tokens)}
    stale = [p for p, text in wanted.items() if not p.exists() or p.read_text() != text]
    if check:
        if stale:
            print("build_tokens: out of date, run python3 scripts/build_tokens.py: "
                  + ", ".join(str(p.relative_to(ROOT)) for p in stale), file=sys.stderr)
            return 1
        print(f"build_tokens: {len(tokens['colors']['dark'])} colours in step with app.css")
        return 0
    for path, text in wanted.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"build_tokens: wrote {len(tokens['colors']['dark'])} colours (dark and light) to "
          + ", ".join(str(p.relative_to(ROOT)) for p in wanted))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
